#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Parse 英文句型_*.md into data.js for the web app.

Features:
- 清理：去掉前導 | / ｜ / > / - / * 等殘留符號，摺疊多餘空白。
- 拆句：把「兩句併一句」（小寫直接接大寫開頭的新句，或逗號後接大寫新句）拆開。
       保護常見詞中大小寫（iPhone / eBay / macOS / McDonald ...）避免誤拆。
- 去重：相同內容（清理後完全一致）只保留一次。
- 編號：以檔名為群組標題（如 A1_001-010），群組內從 1 遞增編號。
"""
import os, re, glob, json

SRC_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP_DIR = os.path.join(SRC_DIR, "app")

LEVEL_META = {
    "A1": {"name": "入門",   "img": "assets/A1_入門.png",   "color": "#3fae9f"},
    "A2": {"name": "基礎",   "img": "assets/A2_基礎.png",   "color": "#e0a23c"},
    "B1": {"name": "中級",   "img": "assets/B1_中級.png",   "color": "#e07b46"},
    "B2": {"name": "中高級", "img": "assets/B2_中高級.png", "color": "#d9574f"},
    "C1": {"name": "高級",   "img": "assets/C1_高級.png",   "color": "#8a6fb0"},
    "C2": {"name": "精通",   "img": "assets/C2_精通.png",   "color": "#4f86c6"},
}
LEVEL_ORDER = ["A1", "A2", "B1", "B2", "C1", "C2"]

line_re = re.compile(r"^\s*(\d+)\.\s*(.+?)\s*$")

# 需在拆句前保護的「詞中大小寫」模式，避免被誤拆
BRAND_PATTERNS = re.compile(
    r"iPhone|iPad|iPod|iTunes|iMac|iWatch|iMessage|iCloud|iPadOS|iOS|"
    r"eBay|macOS|PayPal|YouTube|WeChat|WhatsApp|Gmail|AirPods|AppleTV|"
    r"Mc[A-Za-z]+|O'[A-Z][a-z]+"
)

LEAD_JUNK = re.compile(r"^\s*[|｜>~\-\*•·]\s*")


def protect_brands(text):
    store = {}

    def stash(m):
        key = "\x00%d\x00" % len(store)
        store[key] = m.group(0)
        return key

    tmp = BRAND_PATTERNS.sub(stash, text)
    return tmp, store


def restore_brands(part, store):
    for k, v in store.items():
        part = part.replace(k, v)
    return part


def clean_part(p):
    p = LEAD_JUNK.sub("", p)
    p = p.strip()
    p = re.sub(r"\s{2,}", " ", p)
    p = p.rstrip(",")          # 去掉殘留的尾隨逗號
    p = p.strip()
    return p


def split_merged(text):
    tmp, store = protect_brands(text)
    # 小寫後接「大寫+（小寫或撇號+小寫）」視為新句起頭；逗號後同理
    # 例：sleepingI'm / morningHe / Monday,I
    nxt = r"[A-Z](?:[a-z]|['\u2019][a-z])"
    parts = re.split(r"(?<=[a-z])(?=" + nxt + r")|,(?=" + nxt + r")", tmp)
    out = []
    for p in parts:
        p = restore_brands(p, store)
        p = clean_part(p)
        if p:
            out.append(p)
    return out


def main():
    sentences = []
    groups_order = []
    group_counts = {}
    per_level_count = {lv: 0 for lv in LEVEL_ORDER}
    seen = set()
    split_hits = 0

    files = sorted(glob.glob(os.path.join(SRC_DIR, "英文句型_*.md")))
    for fpath in files:
        base = os.path.basename(fpath)
        m = re.match(r"英文句型_(A1|A2|B1|B2|C1|C2)_", base)
        if not m:
            continue
        level = m.group(1)
        group = re.sub(r"^英文句型_", "", base).replace(".md", "")
        if group not in group_counts:
            group_counts[group] = 0
            groups_order.append(group)
        with open(fpath, encoding="utf-8") as fh:
            for raw in fh:
                mm = line_re.match(raw)
                if not mm:
                    continue
                text = mm.group(2)
                parts = split_merged(text)
                if len(parts) > 1:
                    split_hits += 1
                for p in parts:
                    key = p  # 清理後完全一致才視為重複
                    if key in seen:
                        continue
                    seen.add(key)
                    group_counts[group] += 1
                    per_level_count[level] += 1
                    num = group_counts[group]
                    sentences.append({
                        "id": "%s-%d" % (group, num),
                        "group": group,
                        "level": level,
                        "num": num,
                        "text": p,
                    })

    # 排序：先依群組出現順序，再依群內編號
    gpos = {g: i for i, g in enumerate(groups_order)}
    sentences.sort(key=lambda s: (gpos[s["group"]], s["num"]))

    levels = [{"code": lv, "name": LEVEL_META[lv]["name"],
               "img": LEVEL_META[lv]["img"], "color": LEVEL_META[lv]["color"],
               "count": per_level_count[lv]} for lv in LEVEL_ORDER]
    groups = [{"name": g, "level": g.split("_")[0], "count": group_counts[g]}
              for g in groups_order]

    out = "// AUTO-GENERATED by parse_data.py — do not edit by hand\n"
    out += "const LEVELS = " + json.dumps(levels, ensure_ascii=False, indent=2) + ";\n\n"
    out += "const GROUPS = " + json.dumps(groups, ensure_ascii=False, indent=2) + ";\n\n"
    out += "const SENTENCES = " + json.dumps(sentences, ensure_ascii=False, indent=0) + ";\n"

    with open(os.path.join(APP_DIR, "data.js"), "w", encoding="utf-8") as fh:
        fh.write(out)

    print("Total sentences:", len(sentences))
    print("Total groups:", len(groups_order))
    print("Merged lines split:", split_hits)
    for lv in LEVEL_ORDER:
        print("  %s %s: %d" % (lv, LEVEL_META[lv]["name"], per_level_count[lv]))
    print("Wrote", os.path.join(APP_DIR, "data.js"))


if __name__ == "__main__":
    main()
