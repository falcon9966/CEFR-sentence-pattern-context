#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Parse 英文句型_*.md into data.js for the web app."""
import os, re, glob, json

SRC_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP_DIR = os.path.join(SRC_DIR, "app")

LEVEL_META = {
    "A1": {"name": "入門",   "img": "assets/A1_入門.png",   "color": "#2bb6a3"},
    "A2": {"name": "基礎",   "img": "assets/A2_基礎.png",   "color": "#f6a623"},
    "B1": {"name": "中級",   "img": "assets/B1_中級.png",   "color": "#e8703a"},
    "B2": {"name": "中高級", "img": "assets/B2_中高級.png", "color": "#d64541"},
    "C1": {"name": "高級",   "img": "assets/C1_高級.png",   "color": "#7b5ea7"},
    "C2": {"name": "精通",   "img": "assets/C2_精通.png",   "color": "#3a6ea5"},
}
LEVEL_ORDER = ["A1", "A2", "B1", "B2", "C1", "C2"]

line_re = re.compile(r"^\s*(\d+)\.\s*(.+?)\s*$")

def clean(text):
    t = text.strip()
    # remove stray leading pipe / bullet artifacts
    t = re.sub(r"^\s*[|｜]\s*", "", t)
    # collapse multiple spaces
    t = re.sub(r"\s{2,}", " ", t)
    return t

sentences = []
per_level_count = {lv: 0 for lv in LEVEL_ORDER}

files = sorted(glob.glob(os.path.join(SRC_DIR, "英文句型_*.md")))
for fpath in files:
    base = os.path.basename(fpath)
    m = re.match(r"英文句型_(A1|A2|B1|B2|C1|C2)_", base)
    if not m:
        continue
    level = m.group(1)
    with open(fpath, encoding="utf-8") as fh:
        for raw in fh:
            mm = line_re.match(raw)
            if not mm:
                continue
            text = clean(mm.group(2))
            if not text:
                continue
            per_level_count[level] += 1
            idx = per_level_count[level]
            sentences.append({
                "id": f"{level}-{idx}",
                "level": level,
                "text": text,
            })

# order sentences by level order, then numeric local index
grouped = {lv: [] for lv in LEVEL_ORDER}
for s in sentences:
    grouped[s["level"]].append(s)
ordered = []
for lv in LEVEL_ORDER:
    grouped[lv].sort(key=lambda s: int(s["id"].split("-")[1]))
    ordered.extend(grouped[lv])

levels = [{"code": lv, "name": LEVEL_META[lv]["name"],
           "img": LEVEL_META[lv]["img"], "color": LEVEL_META[lv]["color"],
           "count": per_level_count[lv]} for lv in LEVEL_ORDER]

out = "// AUTO-GENERATED by parse_data.py — do not edit by hand\n"
out += "const LEVELS = " + json.dumps(levels, ensure_ascii=False, indent=2) + ";\n\n"
out += "const SENTENCES = " + json.dumps(ordered, ensure_ascii=False, indent=0) + ";\n"

with open(os.path.join(APP_DIR, "data.js"), "w", encoding="utf-8") as fh:
    fh.write(out)

print("Total sentences:", len(ordered))
for lv in LEVEL_ORDER:
    print(f"  {lv} {LEVEL_META[lv]['name']}: {per_level_count[lv]}")
print("Wrote", os.path.join(APP_DIR, "data.js"))
